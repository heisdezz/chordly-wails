func TestAdversarialInputsDoNotPanic(t *testing.T) {
	adversarial := [][]byte{
		[]byte("{{{{{{{{"),
		[]byte("[[[[[[[["),
		[]byte("=;=;=;=;"),
		[]byte("\t\t\t\t\t\t\t"),
		[]byte("Cookie: =; =; ;;; ==="),
		bytes.Repeat([]byte(";"), 10000),
		[]byte("SAPISID="),
		[]byte("=SAPISID"),
	}

	for i, input := range adversarial {
		// Verify no panic
		_, _ = ParseToken(input)
		_ = i
	}
}
