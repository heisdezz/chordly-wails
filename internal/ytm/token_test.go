func TestParseTokenErrors(t *testing.T) {
	tests := []struct {
		name        string
		input       []byte
		expectedErr error
	}{
		{
			name:        "Empty input",
			input:       []byte(""),
			expectedErr: ErrEmpty,
		},
		{
			name:        "Whitespace only",
			input:       []byte("   \n\t  "),
			expectedErr: ErrEmpty,
		},
		{
			name:        "OAuth ya29 token rejected",
			input:       []byte("ya29.a0AfH6SM..."),
			expectedErr: ErrOAuthTokenUnsupported,
		},
		{
			name:        "Input too large (>2MiB)",
			input:       bytes.Repeat([]byte("a"), 2*1024*1024+1),
			expectedErr: ErrInputTooLarge,
		},
		{
			name:        "Missing SAPISID",
			input:       []byte("SID=123; HSID=456"),
			expectedErr: ErrMissingRequiredCookies,
		},
		{
			name:        "Unrecognized string",
			input:       []byte("not a cookie"),
			expectedErr: ErrUnrecognized,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := ParseToken(tt.input)
			if !errors.Is(err, tt.expectedErr) {
				t.Errorf("ParseToken err = %v, want %v", err, tt.expectedErr)
			}
		})
	}
}

func TestParseRawCookieHeader(t *testing.T) {
	raw := `Cookie: SID=sid_123; HSID=hsid_456; SAPISID=sapisid_abc; __Secure-3PSID=sec_789`
	bundle, err := ParseToken([]byte(raw))
	if err != nil {
		t.Fatalf("ParseToken error: %v", err)
	}

	if bundle.SAPISID != "sapisid_abc" {
		t.Errorf("SAPISID = %q, want %q", bundle.SAPISID, "sapisid_abc")
	}
	if bundle.Cookies["SID"] != "sid_123" {
		t.Errorf("SID cookie = %q, want %q", bundle.Cookies["SID"], "sid_123")
	}
	if bundle.Source != TokenSourceInnerTune && bundle.Source != TokenSourceCookieHeader {
		t.Errorf("Source = %q, want valid cookie source", bundle.Source)
	}
	if !strings.Contains(bundle.Cookie, "SAPISID=sapisid_abc") {
		t.Errorf("Normalized Cookie header missing SAPISID: %s", bundle.Cookie)
	}
}

func TestParseSecureSAPISIDFallback(t *testing.T) {
	// SAPISID is absent, but __Secure-3PAPISID is present
	raw := `SID=sid_123; __Secure-3PAPISID=fallback_sapisid_xyz`
	bundle, err := ParseToken([]byte(raw))
	if err != nil {
		t.Fatalf("ParseToken error: %v", err)
	}

	if bundle.SAPISID != "fallback_sapisid_xyz" {
		t.Errorf("SAPISID fallback = %q, want %q", bundle.SAPISID, "fallback_sapisid_xyz")
	}
	if bundle.Cookies["SAPISID"] != "fallback_sapisid_xyz" {
		t.Errorf("Cookies[SAPISID] not populated from fallback")
	}
}

