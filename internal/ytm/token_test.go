func TestParseNetscapeCookiesTxt(t *testing.T) {
	cookiesTxt := `# Netscape HTTP Cookie File
# https://curl.se/docs/http-cookies.html
# This file was generated by libcurl! Edit at your own risk.

.youtube.com	TRUE	/	TRUE	1799999999	SAPISID	netscape_sapisid
#HttpOnly_.google.com	TRUE	/	TRUE	1799999999	SID	netscape_sid
.google.com	TRUE	/	TRUE	1799999999	__Secure-3PSID	netscape_sec_sid
.otherdomain.org	TRUE	/	FALSE	0	IGNORE	val
`
	bundle, err := ParseToken([]byte(cookiesTxt))
	if err != nil {
		t.Fatalf("ParseToken(Netscape) error: %v", err)
	}

	if bundle.Source != TokenSourceCookiesTxt {
		t.Errorf("Source = %q, want %q", bundle.Source, TokenSourceCookiesTxt)
	}
	if bundle.SAPISID != "netscape_sapisid" {
		t.Errorf("SAPISID = %q, want netscape_sapisid", bundle.SAPISID)
	}
	if bundle.Cookies["SID"] != "netscape_sid" {
		t.Errorf("SID = %q, want netscape_sid", bundle.Cookies["SID"])
	}
	if _, exists := bundle.Cookies["IGNORE"]; exists {
		t.Errorf("Other domain cookie should be ignored")
	}
}

func TestParseJSONBundle(t *testing.T) {
	jsonPayload := `{
		"source": "innertune",
		"cookie": "SID=json_sid; SAPISID=json_sapisid; __Secure-3PSID=json_sec",
		"visitorData": "Cgt_visitor_123",
		"accountName": "Test Music User"
	}`

	bundle, err := ParseToken([]byte(jsonPayload))
	if err != nil {
		t.Fatalf("ParseToken(JSON) error: %v", err)
	}

	if bundle.Source != TokenSourceInnerTune {
		t.Errorf("Source = %q, want %q", bundle.Source, TokenSourceInnerTune)
	}
	if bundle.SAPISID != "json_sapisid" {
		t.Errorf("SAPISID = %q, want json_sapisid", bundle.SAPISID)
	}
	if bundle.VisitorData != "Cgt_visitor_123" {
		t.Errorf("VisitorData = %q, want Cgt_visitor_123", bundle.VisitorData)
	}
	if bundle.AccountName != "Test Music User" {
		t.Errorf("AccountName = %q, want 'Test Music User'", bundle.AccountName)
	}
}

